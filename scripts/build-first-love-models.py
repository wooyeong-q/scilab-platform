"""Create exact, labelled particle diagrams for the science demonstration."""
from PIL import Image, ImageDraw, ImageFont
from pathlib import Path
from io import BytesIO
import base64, json

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 48)
models = {
    'H2': [('H', 145, 140), ('H', 255, 140)],
    'O2': [('O', 145, 140), ('O', 255, 140)],
    'H2O': [('O', 200, 100), ('H', 115, 185), ('H', 285, 185)],
    'CO2': [('C', 200, 140), ('O', 85, 140), ('O', 315, 140)],
    'He': [('He', 200, 140)],
    'O3': [('O', 200, 100), ('O', 115, 185), ('O', 285, 185)],
}
colors = {'H': '#e8edf1', 'O': '#e69181', 'C': '#657f8b', 'He': '#d1b5dc'}
images = {}
for name, atoms in models.items():
    im = Image.new('RGB', (400, 280), '#fffaf0')
    draw = ImageDraw.Draw(im)
    for i in range(1, len(atoms)):
        draw.line((atoms[0][1:], atoms[i][1:]), fill='#6c7779', width=13)
    for symbol, x, y in atoms:
        draw.ellipse((x-49, y-49, x+49, y+49), fill=colors[symbol], outline='#405c65', width=4)
        draw.text((x, y), symbol, font=font, anchor='mm', fill='white' if symbol=='C' else '#243b45')
    out = BytesIO(); im.save(out, format='PNG', optimize=True)
    images[name] = 'data:image/png;base64,'+base64.b64encode(out.getvalue()).decode()
(root/'public/labs/first-love/escape-models.mjs').write_text('// Exact labelled atom counts; generated by scripts/build-first-love-models.py.\nexport const MODELS='+json.dumps(images)+';\n')
